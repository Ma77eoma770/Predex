"""Experimental feature modules, kept OUT of the default feature store.

`registry.py` auto-discovers only `src/features/modules/f_*.py`, so the modules in this
package are not part of the default parquet (feature set v1, 52 columns). They were
evaluated in `src/models/eval_feature_groups.py` and did not improve v1 (see
results/experiments.csv), but are kept for reproducibility and future reuse.

| Module            | Prefix                         | Content                                  |
|-------------------|--------------------------------|------------------------------------------|
| f_p1_team.py      | tm_                            | Player 1 team composition (7 columns)    |
| f_type_matchup.py | ty_off_, ty_def_, ty_act_      | Gen 2 type matchup (18 columns)          |

How to use them on demand (in-process, the default parquet is not touched):

    from src.config import TRAIN_JSONL
    from src.features.experimental import register_experimental
    from src.features.registry import build_feature_dataframe

    names = register_experimental()          # adds them to REGISTRY for this Python process
    X_exp, y = build_feature_dataframe(TRAIN_JSONL, is_train=True, modules=names)

To make them part of the default feature store for everyone, move the file back to
`src/features/modules/` and run `python -m src.features.registry --force` (a team decision:
it changes the columns that scripts loading the whole parquet, e.g. train_logistic.py, see).

They need `data/species_types.csv`, generated by `python -m src.features.build_species_types`.
"""

from typing import List

from src.features.experimental import f_p1_team, f_type_matchup
from src.features.registry import register_module

EXPERIMENTAL_MODULES = {
    "p1_team": f_p1_team.extract_features,
    "type_matchup": f_type_matchup.extract_features,
}


def register_experimental() -> List[str]:
    """Register the experimental extractors in the in-process REGISTRY; return their names."""
    for name, func in EXPERIMENTAL_MODULES.items():
        register_module(name, func)
    return list(EXPERIMENTAL_MODULES)
